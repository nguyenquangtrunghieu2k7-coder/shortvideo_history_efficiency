"""Create publication-friendly plots from the Bloom benchmark CSV reports.

Expected inputs (generated by the benchmark scripts):
  reports/bloom_join_benchmark.csv
  reports/bloom_membership_benchmark.csv

Outputs are written to reports/figures/.
Run from any working directory:
  python scripts/visualize_bloom_results.py
Or provide explicit paths:
  python scripts/visualize_bloom_results.py --reports-dir reports --output-dir reports/figures
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]


def load_single_row(path: Path) -> dict | None:
    if not path.exists():
        print(f"[SKIP] Report not found: {path}")
        return None

    frame = pd.read_csv(path)
    if frame.empty:
        print(f"[SKIP] Report is empty: {path}")
        return None
    if len(frame) > 1:
        print(
            f"[WARN] {path.name} has {len(frame)} rows; "
            "using the first row. These benchmark reports are expected "
            "to contain one aggregate row."
        )
    return frame.iloc[0].to_dict()


def number(row: dict, key: str, default: float = 0.0) -> float:
    value = row.get(key, default)
    if pd.isna(value):
        return default
    return float(value)


def save_bar_chart(
    labels: list[str],
    values: list[float],
    title: str,
    ylabel: str,
    output_path: Path,
    *,
    value_format: str = "{:.3f}",
    rotate: int = 0,
) -> None:
    fig, ax = plt.subplots(figsize=(9, 5.2))
    bars = ax.bar(labels, values)
    ax.set_title(title, fontsize=14, pad=14)
    ax.set_ylabel(ylabel)
    ax.grid(axis="y", linestyle="--", alpha=0.35)
    ax.set_axisbelow(True)
    if rotate:
        ax.tick_params(axis="x", labelrotation=rotate)
    ax.spines[["top", "right"]].set_visible(False)

    max_value = max(values, default=0)
    offset = max_value * 0.025 if max_value > 0 else 0.02
    for bar, value in zip(bars, values):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height() + offset,
            value_format.format(value),
            ha="center",
            va="bottom",
            fontsize=9,
        )

    fig.tight_layout()
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    print(f"[OK] Saved {output_path}")


def plot_join(row: dict, out_dir: Path) -> None:
    # All values are seconds. Bloom total includes build + probe + verification.
    times = [
        number(row, "exact_baseline_s"),
        number(row, "bloom_build_s"),
        number(row, "bloom_probe_s"),
        number(row, "exact_verification_s"),
        number(row, "bloom_total_s"),
    ]
    save_bar_chart(
        ["Exact baseline", "Bloom build", "Bloom probe",
         "Exact verification", "Bloom total"],
        times,
        "KuaiRand Bloom Join: Runtime Breakdown",
        "Time (seconds)",
        out_dir / "bloom_join_runtime.png",
    )

    counts = [
        number(row, "exact_matches"),
        number(row, "bloom_candidates"),
        number(row, "verified_matches"),
        number(row, "records_rejected"),
    ]
    save_bar_chart(
        ["Exact matches", "Bloom candidates", "Verified matches", "Rejected"],
        counts,
        "KuaiRand Bloom Join: Record Counts",
        "Number of history records",
        out_dir / "bloom_join_record_counts.png",
        value_format="{:,.0f}",
        rotate=12,
    )

    fpr_values = [
        number(row, "target_fpr") * 100,
        number(row, "empirical_fpr") * 100,
    ]
    save_bar_chart(
        ["Target FPR", "Empirical FPR"],
        fpr_values,
        "KuaiRand Bloom Join: False Positive Rate",
        "False positive rate (%)",
        out_dir / "bloom_join_fpr.png",
        value_format="{:.4f}%",
    )

    print(
        "[INFO] Join benchmark: "
        f"speedup={number(row, 'speedup'):.3f}x, "
        f"rejection={number(row, 'rejection_ratio'):.2%}, "
        f"false_negatives={number(row, 'false_negatives'):.0f}"
    )


def plot_membership(row: dict, out_dir: Path) -> None:
    # Membership-only timing excludes Bloom build from bloom_pipeline_seconds;
    # keep build time visible as a separate cost.
    times = [
        number(row, "bloom_build_seconds"),
        number(row, "exact_lookup_seconds"),
        number(row, "bloom_lookup_seconds"),
        number(row, "candidate_verification_seconds"),
        number(row, "bloom_pipeline_seconds"),
    ]
    save_bar_chart(
        ["Bloom build", "Exact lookup", "Bloom lookup",
         "Candidate verification", "Bloom lookup + verification"],
        times,
        "KuaiRand Bloom Membership: Runtime Breakdown",
        "Time (seconds)",
        out_dir / "bloom_membership_runtime.png",
        rotate=12,
    )

    counts = [
        number(row, "probe_records"),
        number(row, "exact_matches"),
        number(row, "bloom_candidates"),
        number(row, "verified_matches"),
        number(row, "rejected_records"),
    ]
    save_bar_chart(
        ["Probe records", "Exact matches", "Bloom candidates",
         "Verified matches", "Rejected"],
        counts,
        "KuaiRand Bloom Membership: Record Counts",
        "Number of history interactions",
        out_dir / "bloom_membership_record_counts.png",
        value_format="{:,.0f}",
        rotate=12,
    )

    fpr_values = [
        number(row, "target_fpr") * 100,
        number(row, "theoretical_fpr") * 100,
        number(row, "empirical_fpr") * 100,
    ]
    save_bar_chart(
        ["Target FPR", "Theoretical FPR", "Empirical FPR"],
        fpr_values,
        "KuaiRand Bloom Membership: False Positive Rate",
        "False positive rate (%)",
        out_dir / "bloom_membership_fpr.png",
        value_format="{:.4f}%",
    )

    print(
        "[INFO] Membership benchmark: "
        f"lookup speed ratio="
        f"{number(row, 'exact_over_bloom_lookup_speed_ratio'):.3f}x, "
        f"rejection={number(row, 'rejection_ratio'):.2%}, "
        f"false_negatives={number(row, 'false_negatives'):.0f}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Plot Bloom benchmark CSV reports."
    )
    parser.add_argument(
        "--reports-dir",
        type=Path,
        default=ROOT / "reports",
        help="Directory containing the benchmark CSV files (default: reports/).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Directory for PNG figures (default: reports-dir/figures/).",
    )
    args = parser.parse_args()

    reports_dir = args.reports_dir.resolve()
    output_dir = (
        args.output_dir.resolve()
        if args.output_dir
        else reports_dir / "figures"
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    join_row = load_single_row(
        reports_dir / "bloom_join_benchmark.csv"
    )
    membership_row = load_single_row(
        reports_dir / "bloom_membership_benchmark.csv"
    )

    if join_row is not None:
        plot_join(join_row, output_dir)
    if membership_row is not None:
        plot_membership(membership_row, output_dir)

    if join_row is None and membership_row is None:
        raise FileNotFoundError(
            "No benchmark CSV was found. Expected "
            "bloom_join_benchmark.csv and/or "
            "bloom_membership_benchmark.csv in "
            f"{reports_dir}"
        )

    print(f"\nDone. Figures are in: {output_dir}")


if __name__ == "__main__":
    main()
